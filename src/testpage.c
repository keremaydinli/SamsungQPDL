/*
 * testpage.c - Draw an A4 test page and write it as a QPDL job to stdout.
 *
 *   ./testpage > test.qpdl
 *   lp -d <queue> -o raw test.qpdl
 */
#include "qpdl.h"

#include <stdlib.h>
#include <string.h>

#define RES     600
#define PAGE_W  595.0   /* A4 in points */
#define PAGE_H  842.0

static unsigned char *bm;
static unsigned W, H, STRIDE;

static void px(unsigned x, unsigned y)
{
    if (x < W && y < H)
        bm[(size_t)y * STRIDE + x / 8] |= 0x80 >> (x % 8);
}

static void rect(unsigned x, unsigned y, unsigned w, unsigned h)
{
    for (unsigned j = y; j < y + h; j++)
        for (unsigned i = x; i < x + w; i++)
            px(i, j);
}

static void frame(unsigned x, unsigned y, unsigned w, unsigned h, unsigned t)
{
    rect(x, y, w, t);
    rect(x, y + h - t, w, t);
    rect(x, y, t, h);
    rect(x + w - t, y, t, h);
}

/* 5x7 font, one byte per row, bit 4 = leftmost pixel. */
