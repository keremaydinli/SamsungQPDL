static void text(unsigned x, unsigned y, unsigned scale, const char *s)
{
    for (; *s; s++, x += 6 * scale) {
        const char *c = strchr(glyph_chars, *s);
        if (!c)
            continue;
        const unsigned char *g = glyphs[c - glyph_chars];
        for (unsigned row = 0; row < 7; row++)
            for (unsigned col = 0; col < 5; col++)
                if (g[row] & (0x10 >> col))
                    rect(x + col * scale, y + row * scale, scale, scale);
    }
}

int main(void)
{
    qpdl_job_t job = { getenv("USER"), "QPDL test page", RES, 0, 3 };
    qpdl_page_t page = { RES, RES, 2, 1, PAGE_W, PAGE_H, 1 };

    W = (unsigned)(PAGE_W * RES / 72);
    H = (unsigned)(PAGE_H * RES / 72);
    STRIDE = (W + 7) / 8;
    bm = calloc((size_t)STRIDE * H, 1);
    if (!bm)
        return 1;

    /* Border half an inch from the paper edge */
    frame(300, 300, W - 600, H - 600, 12);

    text(450, 500, 24, "SAMSUNG ML-1675");
    text(450, 800, 14, "MAC DRIVER TEST 1");
    text(450, 1000, 8, "QPDL V5 JBIG 0X15 - 600 DPI - A4");

    /* Solid block, checkerboard, stripes */
    rect(450, 1400, 1000, 1000);
    for (unsigned j = 0; j < 1000; j++)
        for (unsigned i = 0; i < 1000; i++)
            if (((i / 50) + (j / 50)) % 2)
                px(1700 + i, 1400 + j);
    for (unsigned j = 0; j < 1000; j += 40)
        rect(2950, 1400 + j, 1000, 4 + j / 40);

    /* Diagonal line */
    for (unsigned i = 0; i < 3500; i++)
        rect(450 + i, 2700 + i, 6, 6);

    /* Corner markers to check the printable area */
    rect(150, 150, 100, 100);
    rect(W - 250, 150, 100, 100);
    rect(150, H - 250, 100, 100);
    rect(W - 250, H - 250, 100, 100);

    text(450, H - 700, 10, "IF YOU CAN READ THIS IT WORKS");

    qpdl_job_begin(stdout, &job);
    if (qpdl_page(stdout, &page, bm, W, H, STRIDE) < 0) {
        fprintf(stderr, "encoding failed\n");
        return 1;
    }
    qpdl_job_end(stdout);
    free(bm);
    return 0;
}
